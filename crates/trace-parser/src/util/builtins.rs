/// Types that should not be reported as project type dependencies.
pub fn is_builtin_type(name: &str) -> bool {
    matches!(
        name,
        "void"
            | "any"
            | "unknown"
            | "never"
            | "number"
            | "string"
            | "boolean"
            | "bool"
            | "object"
            | "bigint"
            | "symbol"
            | "null"
            | "undefined"
            | "int"
            | "int8"
            | "int16"
            | "int32"
            | "int64"
            | "uint"
            | "uint8"
            | "uint16"
            | "uint32"
            | "uint64"
            | "float"
            | "float32"
            | "float64"
            | "complex64"
            | "complex128"
            | "byte"
            | "rune"
            | "i8"
            | "i16"
            | "i32"
            | "i64"
            | "i128"
            | "isize"
            | "u8"
            | "u16"
            | "u32"
            | "u64"
            | "u128"
            | "usize"
            | "f16"
            | "f32"
            | "f64"
            | "str"
            | "char"
            | "Self"
            | "self"
            | "this"
            | "Unit"
            | "Double"
            | "Float"
            | "Int"
            | "Long"
            | "Short"
            | "Byte"
            | "Boolean"
            | "String"
            | "Char"
            | "Any"
            | "Nothing"
            | "Void"
            | "Never"
            | "Error"
            | "error"
            | "Type"
            | "Map"
            | "List"
            | "Array"
            | "Set"
            | "Option"
            | "Result"
            | "Vec"
            | "Box"
            | "HashMap"
            | "HashSet"
            | "Dictionary"
            | "Optional"
    )
}
